"""Generate throwing PackageManager methods from the operator's SDK API surface.

The generated class implements no service behavior. HeadlessApkContext overrides
only the APK-local metadata operations observed at the original JNI boundary.
"""
import argparse
from pathlib import Path
import re
import subprocess


def generate(api):
    methods = []
    for line in api.splitlines():
        match = re.fullmatch(r"\s*public abstract (.+) (\w+)\((.*)\)( throws [^;]+)?;", line)
        if not match:
            continue
        result, name, parameters, throws = match.groups()
        # javap's generic parameters can contain commas inside angle brackets.
        types, start, depth = [], 0, 0
        for index, char in enumerate(parameters):
            depth += (char == "<") - (char == ">")
            if char == "," and depth == 0:
                types.append(parameters[start:index].strip())
                start = index + 1
        if parameters:
            types.append(parameters[start:].strip())
        arguments = ", ".join(f"{kind} p{index}" for index, kind in enumerate(types))
        declaration = f"    public {result} {name}({arguments}){throws or ''}"
        methods.append(declaration.replace("$", ".") + " {\n"
                       + f'        throw unsupported("{name}({parameters})");\n    }}\n')
    if not methods:
        raise ValueError("No abstract PackageManager methods found")
    return ("// Generated by generate_headless_pm.py; all methods fail explicitly.\n"
            "public class UnsupportedHeadlessPackageManager extends android.content.pm.PackageManager {\n"
            "    public static final java.util.concurrent.atomic.AtomicInteger rejectedCalls =\n"
            "        new java.util.concurrent.atomic.AtomicInteger();\n"
            "    protected static UnsupportedOperationException unsupported(String method) {\n"
            "        rejectedCalls.incrementAndGet();\n"
            '        System.out.println("HEADLESS_UNIMPLEMENTED_PM=" + method);\n'
            "        System.out.flush();\n"
            '        return new UnsupportedOperationException("Headless PackageManager: " + method);\n'
            "    }\n" + "\n".join(methods) + "}\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--javap", required=True)
    parser.add_argument("--android-jar", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    api = subprocess.check_output([args.javap, "-classpath", str(args.android_jar),
                                   "android.content.pm.PackageManager"], text=True)
    with args.output.open("x") as stream:
        stream.write(generate(api))


if __name__ == "__main__":
    main()
